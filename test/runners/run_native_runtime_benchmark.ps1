[CmdletBinding()]
param(
	[string]$GodotPath = "",
	[string]$BaselinePath = "",
	[int]$RunCount = 3
)

$ErrorActionPreference = "Stop"
if ($RunCount -lt 1 -or $RunCount % 2 -eq 0) {
	throw "RunCount must be a positive odd number so the aggregate has a true median."
}

$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$runner = Join-Path $PSScriptRoot "run_godot.ps1"
$benchmarkTempRoot = Join-Path $projectRoot "test\_temp\runtime-benchmark"
$isolatedProject = Join-Path $benchmarkTempRoot ("isolated-{0}" -f [guid]::NewGuid().ToString("N"))
$candidatePaths = @()

New-Item -ItemType Directory -Force -Path (Join-Path $isolatedProject "addons") | Out-Null
Copy-Item -LiteralPath (Join-Path $projectRoot "addons\easing_curve") -Destination (Join-Path $isolatedProject "addons") -Recurse -Force
New-Item -ItemType Directory -Force -Path (Join-Path $isolatedProject "test\scripts\performance") | Out-Null
Copy-Item -LiteralPath (Join-Path $projectRoot "test\scripts\performance\native_v2_vs_tween_benchmark.gd") -Destination (Join-Path $isolatedProject "test\scripts\performance\native_v2_vs_tween_benchmark.gd") -Force
New-Item -ItemType Directory -Force -Path (Join-Path $isolatedProject "test\_temp") | Out-Null
[IO.File]::WriteAllText(
	(Join-Path $isolatedProject "test\_temp\.gdignore"),
	"",
	[Text.UTF8Encoding]::new($false)
)
$projectConfig = @'
; Generated by test/runners/run_native_runtime_benchmark.ps1.
; Only the easing-curve addon and benchmark script are present.
config_version=5

[application]

config/name="Easing Curve Isolated Runtime Benchmark"
config/features=PackedStringArray("4.7", "GL Compatibility")

[rendering]

renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
'@
[IO.File]::WriteAllText(
	(Join-Path $isolatedProject "project.godot"),
	$projectConfig,
	[Text.UTF8Encoding]::new($false)
)

try {
	$bootstrapLog = Join-Path $isolatedProject "test\_temp\bootstrap.log"
	$bootstrapArguments = @("-NoProfile", "-ExecutionPolicy", "Bypass", "-File", $runner)
	if (-not [string]::IsNullOrWhiteSpace($GodotPath)) {
		$bootstrapArguments += @("-GodotPath", $GodotPath)
	}
	$bootstrapArguments += @(
		"--headless", "--editor", "--quit", "--path", $isolatedProject,
		"--log-file", $bootstrapLog
	)
	& (Get-Process -Id $PID).Path @bootstrapArguments
	if ($LASTEXITCODE -ne 0) {
		$classCache = Join-Path $isolatedProject ".godot\global_script_class_cache.cfg"
		$bootstrapOutput = if (Test-Path -LiteralPath $bootstrapLog) {
			Get-Content -Raw -LiteralPath $bootstrapLog
		} else {
			""
		}
		if (
			-not (Test-Path -LiteralPath $classCache) -or
			$bootstrapOutput -match '(?im)(SCRIPT ERROR|Parse Error)'
		) {
			throw "Could not initialize the isolated runtime benchmark project. Log: $bootstrapLog"
		}
		Write-Warning (
			"Bootstrap returned $LASTEXITCODE after producing a clean class cache; continuing."
		)
	}

	for ($run = 1; $run -le $RunCount; $run += 1) {
		$logPath = Join-Path $benchmarkTempRoot ("native_runtime_benchmark_run_{0}.log" -f $run)
		$candidatePaths += $logPath
		$arguments = @("-NoProfile", "-ExecutionPolicy", "Bypass", "-File", $runner)
		if (-not [string]::IsNullOrWhiteSpace($GodotPath)) {
			$arguments += @("-GodotPath", $GodotPath)
		}
		$arguments += @(
			"--headless", "--path", $isolatedProject,
			"--script", "test/scripts/performance/native_v2_vs_tween_benchmark.gd",
			"--log-file", $logPath
		)

		Write-Host "Native runtime benchmark run $run of $RunCount (isolated project)"
		& (Get-Process -Id $PID).Path @arguments
		$exitCode = $LASTEXITCODE
		$log = if (Test-Path -LiteralPath $logPath) { Get-Content -Raw -LiteralPath $logPath } else { "" }
		if ($exitCode -ne 0 -or $log -notmatch '(?m)^BENCHMARK_COMPLETE\|') {
			throw "Native runtime benchmark run $run did not complete successfully. Log: $logPath"
		}
		Write-Host "Native runtime benchmark log: $logPath"
	}
} finally {
	$resolvedBenchmarkRoot = (Resolve-Path -LiteralPath $benchmarkTempRoot).Path
	$resolvedIsolatedProject = (Resolve-Path -LiteralPath $isolatedProject -ErrorAction SilentlyContinue).Path
	if (
		-not [string]::IsNullOrWhiteSpace($resolvedIsolatedProject) -and
		$resolvedIsolatedProject.StartsWith($resolvedBenchmarkRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)
	) {
		Remove-Item -LiteralPath $resolvedIsolatedProject -Recurse -Force
	}
}

$compareArguments = @{ CandidatePath = $candidatePaths }
if (-not [string]::IsNullOrWhiteSpace($BaselinePath)) {
	$compareArguments.BaselinePath = $BaselinePath
}
& (Join-Path $PSScriptRoot "compare_native_benchmark.ps1") @compareArguments
if ($LASTEXITCODE -ne 0) {
	exit $LASTEXITCODE
}
