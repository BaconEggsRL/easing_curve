	"isolated-project-{0}" -f [guid]::NewGuid().ToString("N")
)

function Copy-IsolatedProjectDirectory {
	param(
		[string]$RelativePath,
		[string]$DestinationRoot
	)

	$source = Join-Path $projectRoot $RelativePath
	if (-not (Test-Path -LiteralPath $source -PathType Container)) {
		throw "Required isolated-test source directory was not found: $source"
	}

	$destination = Join-Path $DestinationRoot $RelativePath
	$destinationParent = Split-Path -Parent $destination
	New-Item -ItemType Directory -Force -Path $destinationParent | Out-Null
	Copy-Item -LiteralPath $source -Destination $destination -Recurse -Force
}

function New-IsolatedTestProject {
	param([string]$DestinationRoot)

	New-Item -ItemType Directory -Force -Path $DestinationRoot | Out-Null

	foreach ($relativePath in @(
		"addons\easing_curve",
		"test\scripts",
		"test\presets"
	)) {
		Copy-IsolatedProjectDirectory `
			-RelativePath $relativePath `
			-DestinationRoot $DestinationRoot
	}

	$projectConfig = @'
; Generated by test/runners/run_all_tests.ps1.
; This host intentionally excludes unrelated development plugins and autoloads.
config_version=5

[application]

config/name="Easing Curve Isolated Tests"
config/features=PackedStringArray("4.7", "GL Compatibility")

[editor_plugins]

enabled=PackedStringArray("res://addons/easing_curve/plugin.cfg")

[rendering]

renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
'@
	[IO.File]::WriteAllText(
		(Join-Path $DestinationRoot "project.godot"),
		$projectConfig,
		[Text.UTF8Encoding]::new($false)
	)

	$isolatedTempDirectory = Join-Path $DestinationRoot "test\_temp"
	New-Item -ItemType Directory -Force -Path $isolatedTempDirectory | Out-Null
	[IO.File]::WriteAllText(
		(Join-Path $isolatedTempDirectory ".gdignore"),
		"",
		[Text.UTF8Encoding]::new($false)
	)
}

function Remove-DirectoryIfEmpty {
	param([string]$Path)

	if ([string]::IsNullOrWhiteSpace($Path) -or -not (Test-Path -LiteralPath $Path -PathType Container)) {
		return
	}

	if (-not (Get-ChildItem -LiteralPath $Path -Force | Select-Object -First 1)) {
		Remove-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
	}
}

function Clear-TestTempArtifacts {
	# Keep test/_temp and its tracked .gdignore so Godot does not scan transient
	# test output. Everything else in this directory is runner-owned output.
	New-Item -ItemType Directory -Force -Path $testTempDirectory | Out-Null
	Get-ChildItem -LiteralPath $testTempDirectory -Force |
		Where-Object { $_.Name -ne ".gdignore" } |
		ForEach-Object {
			Remove-Item -LiteralPath $_.FullName -Recurse -Force
		}
}

