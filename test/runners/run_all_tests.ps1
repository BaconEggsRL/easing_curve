function Get-TopLevelDiagnostics {
	param([string[]]$TextSources)

	$diagnostics = @()
	foreach ($text in $TextSources) {
		if ([string]::IsNullOrWhiteSpace($text)) {
			continue
		}
		foreach ($line in ($text -split '\r?\n')) {
			$trimmed = $line.Trim()
			if ($trimmed -match '^(?:SCRIPT ERROR:|ERROR:|WARNING:)') {
				$diagnostics += $trimmed
			}
		}
	}
	return @($diagnostics | Sort-Object -Unique)
}

function Test-DiagnosticAllowed {
	param(
		[string]$Diagnostic,
		[string]$SuiteName,
		[bool]$IsEditor
	)

	if ($Diagnostic -match '^SCRIPT ERROR:') {
		return $false
	}

	foreach ($pattern in $commonGodotDiagnosticPatterns) {
		if ($Diagnostic -match $pattern) {
			return $true
		}
	}

	if ($IsEditor) {
		foreach ($pattern in $commonEditorDiagnosticPatterns) {
			if ($Diagnostic -match $pattern) {
				return $true
			}
		}
	}

	if ($suiteDiagnosticPatterns.ContainsKey($SuiteName)) {
		foreach ($pattern in $suiteDiagnosticPatterns[$SuiteName]) {
			if ($Diagnostic -match $pattern) {
				return $true
			}
		}
	}

	return $false
}

function Initialize-IsolatedTestProject {
	$bootstrapDirectory = Join-Path $runnerTempDirectory (
		"bootstrap-{0}" -f [guid]::NewGuid().ToString("N")
	)
	New-Item -ItemType Directory -Force -Path $bootstrapDirectory | Out-Null

	$stdoutPath = Join-Path $bootstrapDirectory "stdout.txt"
	$stderrPath = Join-Path $bootstrapDirectory "stderr.txt"
	$exitCodePath = Join-Path $bootstrapDirectory "exitcode.txt"
	$godotLogPath = Join-Path $bootstrapDirectory "godot.log"
	$appDataPath = Join-Path $bootstrapDirectory "appdata"
	$initialized = $false

	try {
		$launcherArguments = @(
			"-NoProfile",
			"-ExecutionPolicy", "Bypass",
			"-File", $godotLauncher,
			"-ExitCodeFile", $exitCodePath,
			"-AppDataDirectory", $appDataPath
		)
		if (-not [string]::IsNullOrWhiteSpace($GodotPath)) {
			$launcherArguments += @("-GodotPath", $GodotPath)
		}
		$launcherArguments += @(
			"--editor",
			"--headless",
			"--path", $isolatedProjectDirectory,
			"--import",
			"--log-file", $godotLogPath
		)

		$bootstrapProcess = Start-Process `
			-FilePath $powerShellExecutable `
			-ArgumentList $launcherArguments `
			-WorkingDirectory $isolatedProjectDirectory `
			-RedirectStandardOutput $stdoutPath `
			-RedirectStandardError $stderrPath `
			-WindowStyle Hidden `
			-PassThru

		if (-not $bootstrapProcess.WaitForExit($suiteTimeoutSeconds * 1000)) {
			& taskkill.exe /PID $bootstrapProcess.Id /T /F 2>$null | Out-Null
			throw "Isolated test project bootstrap timed out after $suiteTimeoutSeconds seconds."
		}
		$bootstrapProcess.WaitForExit()

		$stdout = if (Test-Path -LiteralPath $stdoutPath) { Get-Content -Raw -LiteralPath $stdoutPath } else { "" }
		$stderr = if (Test-Path -LiteralPath $stderrPath) { Get-Content -Raw -LiteralPath $stderrPath } else { "" }
		$godotLog = if (Test-Path -LiteralPath $godotLogPath) { Get-Content -Raw -LiteralPath $godotLogPath } else { "" }
		if ($stdout) { Write-Host $stdout.TrimEnd() }
		if ($stderr) { Write-Host $stderr.TrimEnd() }

		if (-not (Test-Path -LiteralPath $exitCodePath -PathType Leaf)) {
			throw "Isolated test project bootstrap did not report an exit code."
		}
		$exitCodeText = (Get-Content -Raw -LiteralPath $exitCodePath).Trim()
		if ($exitCodeText -notmatch '^-?\d+$' -or [int]$exitCodeText -ne 0) {
			throw "Isolated test project bootstrap exited with code '$exitCodeText'."
		}

		$diagnostics = @(Get-TopLevelDiagnostics -TextSources @($stdout, $stderr, $godotLog))
		$unexpectedDiagnostics = @()
		foreach ($diagnostic in $diagnostics) {
			if (-not (Test-DiagnosticAllowed -Diagnostic $diagnostic -SuiteName "" -IsEditor $true)) {
				$unexpectedDiagnostics += $diagnostic
			}
		}
		if ($unexpectedDiagnostics.Count -gt 0) {
			Write-Host "Unexpected isolated-project bootstrap diagnostics:" -ForegroundColor Red
			foreach ($diagnostic in $unexpectedDiagnostics) {
				Write-Host "  $diagnostic" -ForegroundColor Red
			}
			throw "Isolated test project bootstrap reported unexpected diagnostics."
		}

		$classCachePath = Join-Path $isolatedProjectDirectory ".godot\global_script_class_cache.cfg"
		if (-not (Test-Path -LiteralPath $classCachePath -PathType Leaf)) {
			throw "Isolated test project bootstrap did not create the global script class cache."
		}

		$initialized = $true
		Write-Host "Initialized isolated Godot class cache."
	}
	finally {
		if ($initialized) {
			Remove-Item -LiteralPath $bootstrapDirectory -Recurse -Force -ErrorAction SilentlyContinue
		} else {
			Write-Host "Preserved bootstrap artifacts: $bootstrapDirectory" -ForegroundColor Yellow
		}
	}
}

Initialize-IsolatedTestProject

$results = @()
foreach ($suite in $suites) {
	$mode = if ($suite.Editor) { "editor-host" } else { "headless" }
	Write-Host "`n=== $($suite.Name) [$mode] ==="

	$suiteBaseName = [IO.Path]::GetFileNameWithoutExtension($suite.Name)
	$suiteTempDirectory = Join-Path $runnerTempDirectory (
		"{0}-{1}" -f $suiteBaseName, [guid]::NewGuid().ToString("N")
	)
	New-Item -ItemType Directory -Force -Path $suiteTempDirectory | Out-Null
	$stdoutPath = Join-Path $suiteTempDirectory "stdout.txt"
	$stderrPath = Join-Path $suiteTempDirectory "stderr.txt"
	$exitCodePath = Join-Path $suiteTempDirectory "exitcode.txt"
	$godotLogPath = Join-Path $suiteTempDirectory "godot.log"
	$suiteAppDataPath = Join-Path $suiteTempDirectory "appdata"

	$arguments = @()
	if ($suite.Editor) {
		$arguments += "--editor"
	}
	$arguments += @(
		"--headless",
		"--path", $isolatedProjectDirectory,
		"--script", "res://test/scripts/unit/$($suite.Name)",
		"--log-file", $godotLogPath
	)

	$suiteExitCode = -1
	$timedOut = $false
	$passed = $false
	try {
		$suiteTimeout = if ($suite.ContainsKey("TimeoutSeconds")) { $suite.TimeoutSeconds } else { $suiteTimeoutSeconds }
		$launcherArguments = @(
			"-NoProfile",
			"-ExecutionPolicy", "Bypass",
			"-File", $godotLauncher,
			"-ExitCodeFile", $exitCodePath,
			"-AppDataDirectory", $suiteAppDataPath
		)
		if (-not [string]::IsNullOrWhiteSpace($GodotPath)) {
			$launcherArguments += @("-GodotPath", $GodotPath)
		}
		$launcherArguments += $arguments
		$startProcessArguments = @{
			FilePath = $powerShellExecutable
			ArgumentList = $launcherArguments
			WorkingDirectory = $isolatedProjectDirectory
			RedirectStandardOutput = $stdoutPath
			RedirectStandardError = $stderrPath
			WindowStyle = "Hidden"
			PassThru = $true
		}
		$launcherProcess = Start-Process @startProcessArguments
		$completed = $launcherProcess.WaitForExit([int]($suiteTimeout * 1000))
		if ($completed) {
			# Process is already exited; this final wait synchronizes redirected streams.
			$launcherProcess.WaitForExit()
			if (Test-Path -LiteralPath $exitCodePath) {
				$exitCodeText = (Get-Content -Raw -LiteralPath $exitCodePath).Trim()
				if ($exitCodeText -match '^-?\d+$') {
					$suiteExitCode = [int]$exitCodeText
				} else {
					Write-Warning "Invalid exit code from $($suite.Name): '$exitCodeText'"
				}
			} else {
				Write-Warning "No exit code was reported for $($suite.Name)."
			}
		} else {
			$timedOut = $true
			Write-Host "Timed out after $suiteTimeout seconds; terminating process tree rooted at PID $($launcherProcess.Id)." -ForegroundColor Yellow
			& taskkill.exe /PID $launcherProcess.Id /T /F 2>$null | Out-Null
			if (-not $launcherProcess.WaitForExit($killWaitMilliseconds)) {
				Write-Warning (
					"Process tree rooted at PID $($launcherProcess.Id) " +
					"did not exit after taskkill."
				)
			}
		}
		$stdout = if (Test-Path -LiteralPath $stdoutPath) { Get-Content -Raw -LiteralPath $stdoutPath } else { "" }
		$stderr = if (Test-Path -LiteralPath $stderrPath) { Get-Content -Raw -LiteralPath $stderrPath } else { "" }
		$godotLog = if (Test-Path -LiteralPath $godotLogPath) { Get-Content -Raw -LiteralPath $godotLogPath } else { "" }
		$output = "$stdout`n$stderr"
		if ($stdout) { Write-Host $stdout.TrimEnd() }
		if ($stderr) { Write-Host $stderr.TrimEnd() }
		$hasPass = $output -match '(?m)^PASS:'
		$diagnostics = @(Get-TopLevelDiagnostics -TextSources @($stdout, $stderr, $godotLog))
		$allowedDiagnostics = @()
		$unexpectedDiagnostics = @()
		foreach ($diagnostic in $diagnostics) {
			if (Test-DiagnosticAllowed -Diagnostic $diagnostic -SuiteName $suite.Name -IsEditor $suite.Editor) {
				$allowedDiagnostics += $diagnostic
			} else {
				$unexpectedDiagnostics += $diagnostic
			}
		}
		$hasScriptError = @($diagnostics | Where-Object { $_ -match '^SCRIPT ERROR:' }).Count -gt 0
		if ($allowedDiagnostics.Count -gt 0) {
			Write-Host "Allowed diagnostics: $($allowedDiagnostics.Count)"
		}
		if ($unexpectedDiagnostics.Count -gt 0) {
			Write-Host "Unexpected diagnostics:" -ForegroundColor Red
			foreach ($diagnostic in $unexpectedDiagnostics) {
				Write-Host "  $diagnostic" -ForegroundColor Red
			}
		}
		$passed = -not $timedOut -and $suiteExitCode -eq 0 -and $hasPass -and -not $hasScriptError -and $unexpectedDiagnostics.Count -eq 0
		$results += [pscustomobject]@{
			Suite = $suite.Name
			Mode = $mode
			ExitCode = $suiteExitCode
			TimedOut = $timedOut
			PassMarker = $hasPass
			ScriptError = $hasScriptError
			AllowedDiagnostics = $allowedDiagnostics.Count
			UnexpectedDiagnostics = $unexpectedDiagnostics.Count
			Passed = $passed
		}
	} finally {
		if ($passed) {
			Remove-Item -LiteralPath $suiteTempDirectory -Recurse -Force -ErrorAction SilentlyContinue
		} else {
			Write-Host "Preserved temp artifacts: $suiteTempDirectory" -ForegroundColor Yellow
		}
	}
}

Write-Host "`n=== Test summary ==="
$results | Format-Table -AutoSize
$failed = @($results | Where-Object { -not $_.Passed })
if ($failed.Count -gt 0) {
	Write-Host "Preserved isolated test project: $isolatedProjectDirectory" -ForegroundColor Yellow
	Write-Host "$($failed.Count) of $($results.Count) suites failed." -ForegroundColor Red
	exit 1
}

Remove-Item `
	-LiteralPath $isolatedProjectDirectory `
	-Recurse `
	-Force `
	-ErrorAction SilentlyContinue
Remove-DirectoryIfEmpty $runnerTempDirectory

# Keep test/_temp itself: its tracked .gdignore prevents Godot from scanning
# transient test artifacts created beneath this directory.
Write-Host "All $($results.Count) suites passed."
exit 0
