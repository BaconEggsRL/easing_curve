[CmdletBinding()]
param([string]$GodotPath = "")
$ErrorActionPreference = "Stop"

function Resolve-ProjectRoot {
    $candidate = (Resolve-Path $PSScriptRoot).Path
    while ($true) {
        if (Test-Path -LiteralPath (Join-Path $candidate "project.godot") -PathType Leaf) { return $candidate }
        $parent = Split-Path -Parent $candidate
        if ([string]::IsNullOrWhiteSpace($parent) -or $parent -eq $candidate) { throw "Could not locate project.godot above runner directory: $PSScriptRoot" }
        $candidate = $parent
    }
}

function Invoke-GodotRunner {
    param([string[]]$Arguments)
    $runnerArguments = @("-NoProfile", "-ExecutionPolicy", "Bypass", "-File", $godotRunner)
    if (-not [string]::IsNullOrWhiteSpace($GodotPath)) { $runnerArguments += @("-GodotPath", $GodotPath) }
    $runnerArguments += $Arguments
    & $powerShellExecutable @runnerArguments
    return $LASTEXITCODE
}

function Write-IsolatedProjectConfig {
    param([string]$Path, [bool]$EnableBenchmark)
    $plugins = if ($EnableBenchmark) { 'PackedStringArray("res://addons/easing_curve/plugin.cfg", "res://addons/easing_curve_native_crossing_benchmark/plugin.cfg")' } else { 'PackedStringArray("res://addons/easing_curve/plugin.cfg")' }
    $config = @"
; Generated by test/runners/run_native_inspector_crossing_benchmark.ps1.
config_version=5
[application]
config/name="Easing Curve Native Inspector Crossing Benchmark"
config/features=PackedStringArray("4.7", "GL Compatibility")
[editor_plugins]
enabled=$plugins
[rendering]
renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
"@
    [IO.File]::WriteAllText($Path, $config, [Text.UTF8Encoding]::new($false))
}

$projectRoot = Resolve-ProjectRoot
$godotRunner = Join-Path $PSScriptRoot "run_godot.ps1"
$powerShellExecutable = (Get-Process -Id $PID).Path
$tempBase = Join-Path $projectRoot "test\_temp\native-inspector-crossing"
$tempProject = Join-Path $tempBase ([guid]::NewGuid().ToString("N"))
$outputPath = Join-Path $projectRoot "test\_temp\native_inspector_crossing_benchmark.log"
$isolatedTemp = Join-Path $tempProject "test\_temp"
$bootstrapLogPath = Join-Path $isolatedTemp "bootstrap.log"
$editorLogPath = Join-Path $isolatedTemp "native_inspector_editor.log"

New-Item -ItemType Directory -Force -Path $tempProject | Out-Null
foreach ($relativePath in @("addons\easing_curve", "test\scripts")) {
    $source = Join-Path $projectRoot $relativePath
    $destination = Join-Path $tempProject $relativePath
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
    Copy-Item -LiteralPath $source -Destination $destination -Recurse -Force
}

$benchmarkAddon = Join-Path $tempProject "addons\easing_curve_native_crossing_benchmark"
New-Item -ItemType Directory -Force -Path $benchmarkAddon | Out-Null
Copy-Item -LiteralPath (Join-Path $projectRoot "test\scripts\performance\easing_curve_native_inspector_crossing_benchmark.gd") -Destination (Join-Path $benchmarkAddon "plugin.gd") -Force
$benchmarkPluginConfig = @'
[plugin]
name="Easing Curve Native Crossing Benchmark"
description="Temporary native Inspector benchmark host."
author="Easing Curve tests"
version="1.0"
script="plugin.gd"
'@
[IO.File]::WriteAllText((Join-Path $benchmarkAddon "plugin.cfg"), $benchmarkPluginConfig, [Text.UTF8Encoding]::new($false))

New-Item -ItemType Directory -Force -Path $isolatedTemp | Out-Null
[IO.File]::WriteAllText((Join-Path $isolatedTemp ".gdignore"), "", [Text.UTF8Encoding]::new($false))
$projectConfigPath = Join-Path $tempProject "project.godot"
Write-IsolatedProjectConfig -Path $projectConfigPath -EnableBenchmark $false

Write-Host "Bootstrapping isolated editor class cache..."
$bootstrapExit = Invoke-GodotRunner @("--editor", "--headless", "--path", $tempProject, "--import", "--log-file", $bootstrapLogPath)
$classCachePath = Join-Path $tempProject ".godot\global_script_class_cache.cfg"
$bootstrapLog = if (Test-Path -LiteralPath $bootstrapLogPath -PathType Leaf) { Get-Content -Raw -LiteralPath $bootstrapLogPath } else { "" }
$bootstrapHasScriptError = $bootstrapLog -match '(?m)^(?:SCRIPT ERROR:|.*Parse Error:|ERROR: Failed to load script)'
if (-not (Test-Path -LiteralPath $classCachePath -PathType Leaf) -or $bootstrapHasScriptError) {
    if ($bootstrapLog) { Write-Host $bootstrapLog.TrimEnd() }
    Write-Host "Preserved failed benchmark project: $tempProject" -ForegroundColor Yellow
    throw "Native Inspector benchmark bootstrap was invalid (exit code $bootstrapExit)."
}
if ($bootstrapExit -ne 0) { Write-Warning "Bootstrap returned $bootstrapExit, but the class cache exists and no script/parse error was reported; continuing." }

Write-IsolatedProjectConfig -Path $projectConfigPath -EnableBenchmark $true
Write-Host "Running native Inspector crossing benchmark..."
$benchmarkExit = Invoke-GodotRunner @("--editor", "--path", $tempProject, "--log-file", $editorLogPath)
$resultPath = Join-Path $isolatedTemp "native_inspector_crossing_benchmark.log"
if (Test-Path -LiteralPath $resultPath -PathType Leaf) {
    Copy-Item -LiteralPath $resultPath -Destination $outputPath -Force
    Write-Host ""
    Get-Content -LiteralPath $resultPath
    Write-Host ""
    Write-Host "Benchmark log: $outputPath"
}

$passed = ($benchmarkExit -eq 0) -and (Test-Path -LiteralPath $resultPath -PathType Leaf)
if ($passed) { $passed = (Get-Content -Raw -LiteralPath $resultPath) -match 'NATIVE_INSPECTOR_DONE\|.+\|PASS' }
if (-not $passed) {
    if (Test-Path -LiteralPath $editorLogPath -PathType Leaf) { Write-Host (Get-Content -Raw -LiteralPath $editorLogPath).TrimEnd() }
    Write-Host "Preserved failed benchmark project: $tempProject" -ForegroundColor Yellow
    exit 1
}
Remove-Item -LiteralPath $tempProject -Recurse -Force -ErrorAction SilentlyContinue
if ((Test-Path -LiteralPath $tempBase -PathType Container) -and -not (Get-ChildItem -LiteralPath $tempBase -Force | Select-Object -First 1)) { Remove-Item -LiteralPath $tempBase -Force -ErrorAction SilentlyContinue }
Write-Host "Native Inspector crossing benchmark passed."
exit 0
